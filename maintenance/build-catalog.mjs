import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import { lexer } from '../vendor/marked.cjs';
import {staticPages} from './static-pages.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const catalog = JSON.parse(read('data/articles.json'));
const html = s => String(s).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const md = s => String(s).replace(/[\\[\]]/g, '\\$&');
const byId = new Map(catalog.articles.map(a => [a.id, a]));
assert.equal(byId.size, catalog.articles.length, 'Duplicate article ID');
const topicIds = new Set(catalog.topics.map(t => t.id));
assert.equal(topicIds.size, catalog.topics.length);
const files = fs.readdirSync(path.join(root,'docs')).filter(f => /^\d+\.md$/.test(f)).map(f => Number(f.slice(0,-3))).sort((a,b)=>a-b);
assert.deepEqual([...byId.keys()].sort((a,b)=>a-b), files, 'Every numbered article needs metadata');
for (const a of catalog.articles) {
  assert.ok(Number.isInteger(a.id) && a.id > 0);
  for (const field of ['title','originalTitle','versionNote']) assert.ok(typeof a[field] === 'string' && a[field].trim(), `${a.id}: ${field}`);
  assert.ok(/[\u3400-\u9fff]/.test(a.title), `${a.id}: missing Chinese title`);
  assert.ok(a.topics.length && a.topics.every(t => topicIds.has(t)), `${a.id}: topic`);
  assert.ok(catalog.types[a.type] && Array.isArray(a.aliases) && a.aliases.every(x=>typeof x==='string'));
  assert.ok(a.type === 'editorial' ? a.series === null : catalog.series[a.series], `${a.id}: series required`);
  assert.equal(new URL(a.source.url).protocol, 'https:');
  assert.ok(a.source.label && a.validation.note);
  assert.ok(['tested','not-recorded'].includes(a.validation.status));
  if (a.validation.record) assert.ok(fs.existsSync(path.join(root, a.validation.record.slice(1))), `${a.id}: missing validation record`);
  if (a.validation.status === 'tested') {
    assert.ok(a.validation.record && a.validation.date, `${a.id}: evidence required`);
    assert.ok(fs.existsSync(path.join(root, a.validation.record.slice(1))));
  }
}
assert.equal(new Set(catalog.paths.map(p=>p.id)).size,catalog.paths.length,'Unique path IDs required');
for (const p of catalog.paths) {
  assert.ok(/^[a-z-]+$/.test(p.id) && p.goal && p.description);
  assert.ok(p.articles.length && p.articles.every(id=>byId.has(id)));
  assert.equal(new Set(p.articles).size,p.articles.length,`${p.id}: repeated path article`);
}
assert.ok(catalog.featured.every(id=>byId.has(id)));
const link = id => `[${md(byId.get(id).title)}](/docs/${id}.md)`;
const articleLink = a => `<a href="#/docs/${a.id}">${html(a.title)}</a>`;
const seriesLabel = a => a.series ? catalog.series[a.series].title : catalog.types[a.type];
const banner = '<!-- Generated by maintenance/build-catalog.mjs. Edit data/articles.json instead. -->\n\n';
const statistics = {total:catalog.articles.length,technical:catalog.articles.filter(a=>a.type!=='editorial').length,
  editorial:catalog.articles.filter(a=>a.type==='editorial').length,topics:catalog.topics.length,paths:catalog.paths.length};
const topicItems = catalog.topics.map((t,i)=>{
  const entries=catalog.articles.filter(a=>a.topics.includes(t.id));
  const primary=entries.filter(a=>a.topics[0]===t.id).length;
  return `<a class="topic-card" href="#/docs/topics?id=topic-${t.id}" data-docs-route="/docs/topics?id=topic-${t.id}" title="${entries.length} 篇收录，${primary} 篇主归属"><span class="topic-index">${String(i+1).padStart(2,'0')}</span><span class="topic-copy"><strong>${html(t.title)}</strong><span>${html(t.description)}</span></span><span class="topic-count">${entries.length}<span class="sr-only"> 篇收录，${primary} 篇主归属</span></span><span class="icon icon-arrow-up-right" aria-hidden="true"></span></a>`;
}).join('\n');
const outputs = new Map();
let sidebar = '* **PostgreSQL Howto 中文版**\n  * [首页](/README.md)\n  * [全部文章](/docs/find.md)\n  * [专题](/docs/topics.md)\n  * [学习路径](/docs/paths.md)\n  * [会议精选](/docs/conferences.md)\n';
let topics = `# 专题\n\n${statistics.technical} 篇技术文章 · ${statistics.editorial} 篇项目后记 · ${statistics.topics} 个专题。下列数量含跨专题收录；侧栏数量只计算主归属文章。\n\n<div class="topic-grid">\n${topicItems}\n</div>\n`;
sidebar = sidebar.replace('  * [会议精选]', '  * [系列阅读](/docs/series.md)\n  * [会议精选]');
for (const t of catalog.topics) {
  const entries = catalog.articles.filter(a=>a.topics.includes(t.id));
  sidebar += `\n* **${t.title}**\n` + catalog.articles.filter(a=>a.topics[0] === t.id).map(a=>`  * [${a.id}. ${md(a.title)}](/docs/${a.id}.md)`).join('\n') + '\n';
}
for (const t of catalog.topics) topics += `\n<span id="topic-${t.id}"></span>\n\n## ${t.title}\n\n${t.description}\n\n收录 ${catalog.articles.filter(a=>a.topics.includes(t.id)).length} 篇 · 主归属 ${catalog.articles.filter(a=>a.topics[0]===t.id).length} 篇\n\n` + catalog.articles.filter(a=>a.topics.includes(t.id)).map(a=>`- ${link(a.id)} · ${catalog.types[a.type]}`).join('\n') + '\n';
outputs.set('_sidebar.md',banner+sidebar);
outputs.set('docs/topics.md',banner+topics);
outputs.set('docs/series.md',banner+'# 系列阅读\n\n'+Object.entries(catalog.series).map(([id,s])=>{
  const articles=catalog.articles.filter(a=>a.series===id).sort((a,b)=>(b.addedOn||'').localeCompare(a.addedOn||'') || a.id-b.id);
  return `## ${s.title}\n\n${s.description}\n\n`+articles.slice(0,6).map(a=>`- ${link(a.id)} · ${catalog.types[a.type]}`).join('\n')+`\n\n[全部 ${articles.length} 篇](/docs/find.md?series=${id})`;
}).join('\n\n')+'\n');
outputs.set('docs/paths.md', banner+'# 学习路径\n\n从判断依据到具体操作，沿现有文章逐步深入。\n\n<div class="path-grid">\n'+catalog.paths.map((p,i)=>`<section class="path-card" id="path-${p.id}"><p class="path-eyebrow">路径 ${String(i+1).padStart(2,'0')} · ${p.articles.length} 篇</p><h2>${html(p.title)}</h2><p>${html(p.description)}</p><p class="path-goal">${html(p.goal)}</p><ol>${p.articles.map(id=>`<li>${articleLink(byId.get(id))}</li>`).join('')}</ol></section>`).join('\n')+'\n</div>\n');
outputs.set('docs/conferences.md',banner+'# 会议精选\n\n按会议回溯来源，文章同时归入对应技术专题。\n'+catalog.articles.filter(a=>a.type==='conference').sort((a,b)=>b.source.date.localeCompare(a.source.date)).map(a=>`\n## ${a.source.event}\n\n### ${link(a.id)}\n\n${a.source.label} · ${a.source.date}\n\n原题：${a.originalTitle}\n\n${a.versionNote} ${a.validation.note}\n\n[原始材料](${a.source.url}) · ${link(a.id)}\n`).join(''));
outputs.set('docs/find.md',banner+'# 全部文章\n\n<div class="article-finder" data-finder></div>\n\n[浏览专题](/docs/topics.md) · [学习路径](/docs/paths.md)\n');
const discovery = '<div class="article-finder" data-finder data-home></div>';
const problems = `<div class="problem-links" aria-label="按问题查找">${catalog.problems.map(p=>`<a href="#/docs/find?q=${encodeURIComponent(p.query)}">${html(p.title)}<span class="icon icon-arrow-up-right" aria-hidden="true"></span></a>`).join('')}</div>`;
const recent = catalog.featured.map(id=>byId.get(id));
for (const a of recent) assert.ok(/^\d{4}-\d{2}-\d{2}$/.test(a.addedOn) && new Date(a.addedOn).toISOString().slice(0,10) === a.addedOn, `${a.id}: valid addedOn required`);
recent.sort((a,b)=>b.addedOn.localeCompare(a.addedOn) || b.id-a.id);
const featured = '<section class="home-section" aria-labelledby="home-recent"><div class="section-heading"><div><p class="section-eyebrow">LATEST</p><h2 id="home-recent">最近收录</h2></div><a href="#/docs/find">全部文章 <span class="icon icon-arrow-up-right" aria-hidden="true"></span></a></div><ul class="recent-articles">\n'+recent.map(a=>`<li><time datetime="${a.addedOn}">${a.addedOn}</time><div>${articleLink(a)}<span>${html(catalog.topics.find(t=>t.id===a.topics[0]).title)} · ${seriesLabel(a)} · ${catalog.types[a.type]}</span></div></li>`).join('\n')+'\n</ul></section>\n';
const template = read('maintenance/home-template.md');
const replacements={HOME_DISCOVERY:discovery,HOME_FEATURED:featured,HOME_PROBLEMS:problems,
  HOME_STATS:`<p class="home-stats"><span><strong>${statistics.technical}</strong> 篇技术文章</span><span><strong>${statistics.topics}</strong> 个专题</span><span><strong>${statistics.paths}</strong> 条学习路径</span></p>`,
  HOME_TOPICS:`<div class="topic-grid">${topicItems}</div>`,
  HOME_PATHS:`<div class="home-paths">${catalog.paths.map((p,i)=>`<a href="#/docs/paths?id=path-${p.id}"><span class="path-number">${String(i+1).padStart(2,'0')}</span><span><strong>${html(p.title)}</strong><span>${html(p.goal)}</span></span><small>${p.articles.length} 篇</small><span class="icon icon-arrow-up-right" aria-hidden="true"></span></a>`).join('')}</div>`};
let home=template;
for (const [key,value] of Object.entries(replacements)) {
  assert.equal(home.split(`<!-- ${key} -->`).length,2,`${key}: one marker required`);
  home=home.replace(`<!-- ${key} -->`,value);
}
outputs.set('docs/home.md',banner+home);
let readme=read('maintenance/readme-template.md');
for(const [key,value] of Object.entries({TOPICS:catalog.topics.map(t=>`- [${t.title}](https://postgres-howto.cn/#/docs/topics?id=topic-${t.id})`).join('\n'),PATHS:catalog.paths.map(p=>`- [${p.title}](https://postgres-howto.cn/#/docs/paths?id=path-${p.id})`).join('\n'),RECENT:recent.map(a=>`- ${a.addedOn} · [${md(a.title)}](https://postgres-howto.cn/articles/${a.id}/)`).join('\n')}))readme=readme.replace(`<!-- ${key} -->`,value);
outputs.set('README.md',banner+readme);
outputs.set('docs/about.md',banner+read('maintenance/about-template.md'));
outputs.set('docs/not-found.md',banner+'# 没有找到这篇文章\n\n链接可能不完整，或文章尚未收录。\n\n[查找文章](/docs/find.md) · [专题索引](/docs/topics.md) · [返回首页](/README.md)\n');
outputs.set('robots.txt','User-agent: *\nAllow: /\nSitemap: https://postgres-howto.cn/sitemap.xml\n');
function searchText(tokens) {
  return tokens.map(token=>{
    if (token.type==='table') return [...token.header,...token.rows.flat()].map(cell=>searchText(cell.tokens)).join(' ');
    if (token.type==='list') return token.items.map(item=>searchText(item.tokens)).join(' ');
    if (token.tokens) return searchText(token.tokens);
    if (token.type==='html') return token.text.replace(/<!--[^]*?-->/g,' ').replace(/<[^>]*>/g,' ');
    return token.text || '';
  }).join(' ');
}
const index = catalog.articles.map(a=>({id:a.id,text:searchText(lexer(read(`docs/${a.id}.md`)))
  .replace(/https?:\/\/[^\s)]+/g,' ').replace(/\s+/g,' ').trim()}));
const revision = createHash('sha256').update(JSON.stringify(catalog)+JSON.stringify(index)).digest('hex').slice(0,16);
outputs.set('data/search-index.json', JSON.stringify({revision,articles:index})+'\n');
outputs.set('scripts/catalog-data.js', '// Generated; do not edit.\nwindow.HowtoCatalog = '+JSON.stringify({...catalog,statistics,revision}).replaceAll('<','\\u003c')+';\n');
let entry = read('index.html');
for (const asset of ['scripts/catalog-data.js','scripts/search-core.js','scripts/article-view.js','scripts/site.js','scripts/finder.js','scripts/diagrams.js','scripts/reading.js','scripts/comments.js','styles/custom.css','styles/reading.css']) {
  const hash=createHash('sha256').update(outputs.get(asset) || read(asset)).digest('hex').slice(0,16);
  const pattern=new RegExp('(\\./'+asset.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')+')(?:\\?v=[^"\\s]+)?(?=")','g');
  assert.ok(pattern.test(entry),'Missing asset reference: '+asset);
  pattern.lastIndex=0;
  entry=entry.replace(pattern,'$1?v='+hash);
}
outputs.set('index.html',entry);
staticPages(catalog,read,outputs);
let stale = false;
for (const [file,text] of outputs) {
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(path.join(root,file)) || read(file)!==text) { console.error('Out of date:',file); stale=true; }
  } else {
    fs.mkdirSync(path.dirname(path.join(root,file)),{recursive:true});
    fs.writeFileSync(path.join(root,file),text);
  }
}
if (stale) process.exitCode=1;
else console.log(`${catalog.articles.length} article records validated; ${outputs.size} generated files ${process.argv.includes('--check')?'verified':'updated'} (${revision}).`);
